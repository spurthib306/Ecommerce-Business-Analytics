"""Step 4 - build the Excel workbook (Excel-Analysis/ecommerce_analysis.xlsx).

Sheets: data-quality checks, cleaning log, import/validation checks (with live
Excel formulas), KPI summary, analysis tables with native Excel charts, and a
1,000-order sample with SUMIFS/COUNTIFS formulas you can inspect and extend.
Opens in Excel for Windows, Excel for Mac, LibreOffice and Google Sheets.
"""
import sys

import pandas as pd
from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.table import Table, TableStyleInfo

from config import CLEAN_DIR, EXCEL_DIR, RESULTS_DIR, SAMPLE_DIR, ensure_dirs

HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14, color="1F3A5F")
NOTE_FONT = Font(italic=True, color="595959")
MONEY = '#,##0.00'
INT = '#,##0'
PCT_NUM = '0.00"%"'   # values already in percent units (e.g. 6.79)


def res(name):
    return pd.read_csv(RESULTS_DIR / f"{name}.csv")


def number_format_for(col):
    c = col.lower()
    if "pct" in c or "share" in c:
        return PCT_NUM
    if any(k in c for k in ("revenue", "value", "aov", "price", "freight", "paid", "payment", "items_plus")):
        return MONEY
    if any(k in c for k in ("orders", "customers", "items", "rows", "count", "rank")):
        return INT
    return None


def write_table(ws, df, start_row=1, start_col=1, name=None, title=None, note=None):
    """Write df as a formatted Excel Table. Returns (first_data_row, last_row)."""
    r = start_row
    if title:
        ws.cell(row=r, column=start_col, value=title).font = TITLE_FONT
        r += 1
    if note:
        ws.cell(row=r, column=start_col, value=note).font = NOTE_FONT
        r += 1
    header_row = r
    for j, col in enumerate(df.columns):
        cell = ws.cell(row=r, column=start_col + j, value=col)
        cell.fill, cell.font = HEADER_FILL, HEADER_FONT
        cell.alignment = Alignment(wrap_text=True, vertical="center")
    for i, row in enumerate(df.itertuples(index=False), start=1):
        for j, v in enumerate(row):
            if isinstance(v, float) and pd.isna(v):
                v = None
            cell = ws.cell(row=r + i, column=start_col + j, value=v)
            fmt = number_format_for(df.columns[j])
            if fmt and isinstance(v, (int, float)):
                cell.number_format = fmt
    last_row = r + len(df)
    if name and len(df):
        ref = f"{get_column_letter(start_col)}{header_row}:{get_column_letter(start_col + len(df.columns) - 1)}{last_row}"
        t = Table(displayName=name, ref=ref)
        t.tableStyleInfo = TableStyleInfo(name="TableStyleLight9", showRowStripes=True)
        ws.add_table(t)
    for j, col in enumerate(df.columns):
        width = max(len(str(col)), *(len(str(x)) for x in df.iloc[:, j].head(200))) if len(df) else len(col)
        letter = get_column_letter(start_col + j)
        ws.column_dimensions[letter].width = max(ws.column_dimensions[letter].width or 0, min(width + 2, 60))
    return header_row + 1, last_row


def add_bar(ws, anchor, title, cats_ref, vals_ref, horizontal=True, y_title=None):
    ch = BarChart()
    ch.type = "bar" if horizontal else "col"
    ch.title, ch.legend, ch.height, ch.width = title, None, 9, 18
    ch.add_data(vals_ref, titles_from_data=True)
    ch.set_categories(cats_ref)
    if horizontal:
        ch.y_axis.scaling.orientation = "minMax"
        ch.x_axis.scaling.orientation = "maxMin"  # largest bar on top
    if y_title:
        ch.y_axis.title = y_title
    ws.add_chart(ch, anchor)


