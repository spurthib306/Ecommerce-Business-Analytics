def sheet_validation(wb):
    ws = wb.create_sheet("Validation")
    counts = res("00_import_row_counts")
    first, last = write_table(ws, counts, title="Row counts after database import",
                              note="CSV rows vs rows in the database. Status is an Excel formula.", name="RowCounts")
    for r in range(first, last + 1):
        ws.cell(row=r, column=4, value=f'=IF(B{r}=C{r},"OK","CHECK")')
    checks = res("00_validation_checks")
    start = last + 3
    first, last = write_table(ws, checks, start_row=start, title="Cross-checks",
                              note="value_a and value_b are computed independently; difference and status are formulas.",
                              name="CrossChecks")
    for r in range(first, last + 1):
        ws.cell(row=r, column=4, value=f"=ROUND(B{r}-C{r},2)").number_format = MONEY
        ws.cell(row=r, column=5, value=f'=IF(ABS(D{r})<=1,"MATCH","CHECK")')
        for col in (2, 3):
            ws.cell(row=r, column=col).number_format = MONEY
    rec = res("14_reconciliation")
    write_table(ws, rec, start_row=last + 3, title="Payments reconciliation",
                note="Items + freight vs payments recorded. Small gap = vouchers / instalment interest.")


def sheet_kpis(wb):
    ws = wb.create_sheet("KPIs")
    k = res("02_kpi_overview").iloc[0]
    y = res("04_yoy_growth").iloc[0]
    rows = [
        ("Total revenue (R$)", k.total_revenue, MONEY),
        ("Total freight (R$)", k.total_freight, MONEY),
        ("Distinct orders", k.distinct_orders, INT),
        ("Average order value (R$)", k.average_order_value, MONEY),
        ("Distinct customers", k.distinct_customers, INT),
        ("Items sold", k.items_sold, INT),
        ("Average review score (1-5)", k.avg_review_score, "0.00"),
        ("Late delivery rate", k.late_delivery_pct, PCT_NUM),
        ("Average delivery time (days)", k.avg_delivery_days, "0.0"),
        ("Revenue Jan-Aug 2017 (R$)", y.revenue_jan_aug_2017, MONEY),
        ("Revenue Jan-Aug 2018 (R$)", y.revenue_jan_aug_2018, MONEY),
        ("Year-over-year revenue growth", y.revenue_growth_pct, PCT_NUM),
    ]
    ws.cell(row=1, column=1, value="Headline KPIs").font = TITLE_FONT
    for i, (label, value, fmt) in enumerate(rows, start=3):
        ws.cell(row=i, column=1, value=label).font = Font(bold=True)
        c = ws.cell(row=i, column=2, value=float(value))
        c.number_format = fmt
    ws.cell(row=len(rows) + 4, column=1, value="AOV check (formula): revenue / orders").font = NOTE_FONT
    ws.cell(row=len(rows) + 4, column=2, value="=B3/B5").number_format = MONEY
    ws.column_dimensions["A"].width = 36
    ws.column_dimensions["B"].width = 18


def sheet_with_chart(wb, title, df, chart_title, cat_col, val_col, horizontal=True, top=None, line=False,
                     table_name=None, note=None):
    ws = wb.create_sheet(title)
    first, last = write_table(ws, df, title=title.replace("_", " "), note=note, name=table_name)
    n = len(df) if top is None else min(top, len(df))
    ci = list(df.columns).index(cat_col) + 1
    vi = list(df.columns).index(val_col) + 1
    cats = Reference(ws, min_col=ci, min_row=first, max_row=first + n - 1)
    vals = Reference(ws, min_col=vi, min_row=first - 1, max_row=first + n - 1)
    anchor = f"{get_column_letter(len(df.columns) + 2)}2"
    if line:
        ch = LineChart()
        ch.title, ch.legend, ch.height, ch.width = chart_title, None, 9, 20
        ch.add_data(vals, titles_from_data=True)
        ch.set_categories(cats)
        ws.add_chart(ch, anchor)
    else:
        add_bar(ws, anchor, chart_title, cats, vals, horizontal=horizontal)
    return ws


def sheet_sample(wb):
    items = pd.read_csv(SAMPLE_DIR / "order_items.csv", dtype={"order_id": str, "product_id": str})
    products = pd.read_csv(SAMPLE_DIR / "products.csv", dtype={"product_id": str})
    orders = pd.read_csv(SAMPLE_DIR / "orders.csv", dtype={"order_id": str, "customer_id": str})
    customers = pd.read_csv(SAMPLE_DIR / "customers.csv", dtype={"customer_id": str})
    df = (items.merge(products[["product_id", "category"]], on="product_id", how="left")
               .merge(orders[["order_id", "customer_id", "order_status", "order_purchase_timestamp"]], on="order_id")
               .merge(customers[["customer_id", "customer_state"]], on="customer_id"))
    df = df[["order_id", "order_item_id", "order_purchase_timestamp", "order_status", "customer_state",
             "category", "price", "freight_value"]].sort_values(["order_purchase_timestamp", "order_id"])
    df["order_id"] = df["order_id"].str[:12]  # shortened for readability
    df["line_total"] = None  # filled with formulas below
    ws = wb.create_sheet("Sales_Sample")
    first, last = write_table(ws, df, name="SalesSample", title="Sales sample (1,000 random orders in scope)",
                              note="One row per order item. line_total is an Excel formula: price + freight.")
    col = len(df.columns)
    for r in range(first, last + 1):
        ws.cell(row=r, column=col, value=f"=G{r}+H{r}").number_format = MONEY

    ws2 = wb.create_sheet("Sample_Summary")
    ws2.cell(row=1, column=1, value="Sample summary with SUMIFS / COUNTIFS").font = TITLE_FONT
    ws2.cell(row=2, column=1, value="Valid sales only (status not canceled/unavailable). Edit a category to see formulas recalculate.").font = NOTE_FONT
    headers = ["category", "revenue (SUMIFS)", "items (COUNTIFS)", "avg item price"]
    for j, h in enumerate(headers, start=1):
        c = ws2.cell(row=4, column=j, value=h)
        c.fill, c.font = HEADER_FILL, HEADER_FONT
    top = (df[~df.order_status.isin(["canceled", "unavailable"])]
           .groupby("category")["price"].sum().sort_values(ascending=False).head(15).index)
    s_rng = f"Sales_Sample!$F${first}:$F${last}"
    p_rng = f"Sales_Sample!$G${first}:$G${last}"
    st_rng = f"Sales_Sample!$D${first}:$D${last}"
    for i, cat in enumerate(top, start=5):
        ws2.cell(row=i, column=1, value=cat)
        ws2.cell(row=i, column=2, value=(f'=SUMIFS({p_rng},{s_rng},A{i},{st_rng},"<>canceled",{st_rng},"<>unavailable")')).number_format = MONEY
        ws2.cell(row=i, column=3, value=(f'=COUNTIFS({s_rng},A{i},{st_rng},"<>canceled",{st_rng},"<>unavailable")')).number_format = INT
        ws2.cell(row=i, column=4, value=f"=IFERROR(B{i}/C{i},0)").number_format = MONEY
    end = 4 + len(top)
    ws2.cell(row=end + 1, column=1, value="Total (top 15)").font = Font(bold=True)
    ws2.cell(row=end + 1, column=2, value=f"=SUM(B5:B{end})").number_format = MONEY
    ws2.cell(row=end + 1, column=3, value=f"=SUM(C5:C{end})").number_format = INT
    for letter, w in zip("ABCD", (32, 18, 16, 16)):
        ws2.column_dimensions[letter].width = w


def main():
    ensure_dirs()
    if not (RESULTS_DIR / "02_kpi_overview.csv").exists():
        print("[excel] SQL results not found. Run step 3 first.")
        return 1
    wb = Workbook()
    sheet_readme(wb)
    dq = wb.create_sheet("Data_Quality")
    write_table(dq, pd.read_csv(CLEAN_DIR / "data_quality_profile.csv"), name="DataQuality",
                title="Raw data quality profile", note="Grain and key were verified: duplicate_key_rows should be 0.")
    cl = wb.create_sheet("Cleaning_Log")
    write_table(cl, pd.read_csv(CLEAN_DIR / "cleaning_log.csv"), name="CleaningLog", title="Cleaning log")
    sheet_validation(wb)
    sheet_kpis(wb)

    monthly = res("03_monthly_revenue")
    monthly["order_month"] = pd.to_datetime(monthly["order_month"]).dt.strftime("%Y-%m")
    sheet_with_chart(wb, "Monthly_Revenue", monthly, "Monthly revenue (R$)", "order_month", "revenue",
                     line=True, table_name="MonthlyRevenue")
    sheet_with_chart(wb, "Categories", res("05_category_revenue"), "Top 10 categories by revenue (R$)",
                     "category", "revenue", top=10, table_name="Categories")
    sheet_with_chart(wb, "Category_Profile", res("06_high_value_low_volume"),
                     "Revenue share / order share (categories with 300+ orders)", "category",
                     "revenue_to_volume_ratio", top=12, table_name="CategoryProfile",
                     note="Ratio >= 1.5: the category's share of revenue is at least 1.5x its share of orders.")
    sheet_with_chart(wb, "Regions", res("08_revenue_by_region"), "Revenue by region (R$)",
                     "customer_region", "revenue", table_name="Regions")
    sheet_with_chart(wb, "States", res("07_revenue_by_state"), "Top 10 states by revenue (R$)",
                     "customer_state", "revenue", top=10, table_name="States")
    sheet_with_chart(wb, "Delivery", res("10_delivery_by_state"), "Late delivery rate by state (%)",
                     "customer_state", "late_delivery_pct", top=10, table_name="DeliveryByState",
                     note="Delivered orders only. States with few orders (e.g. RR, AP) have unstable rates.")
    sheet_with_chart(wb, "Reviews_vs_Delivery", res("11_reviews_vs_delivery"),
                     "Average review score by delivery timeliness", "delivery_bucket", "avg_review",
                     horizontal=False, table_name="ReviewsVsDelivery")
    cust = wb.create_sheet("Customers")
    write_table(cust, res("12_repeat_customers"), name="RepeatCustomers", title="Repeat purchase behaviour",
                note="customer_unique_id identifies a person; customer_id is issued per order.")
    pay = wb.create_sheet("Payments")
    write_table(pay, res("13_payment_mix"), name="PaymentMix", title="Payment methods (valid sales)")
    sheet_sample(wb)

    out = EXCEL_DIR / "ecommerce_analysis.xlsx"
    wb.save(out)
    print(f"[excel] Workbook saved: {out} ({len(wb.sheetnames)} sheets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
